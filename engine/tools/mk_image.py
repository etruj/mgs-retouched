#!/usr/bin/env python3
"""Build-time extraction from the original MGSTUS:
  gen/image.bin     vm bytes 0x1000..0x89000, bss zero-filled, loaded into wasm memory
                    at the same addresses so the verified C's fixed addresses resolve
  gen/image_meta.c  binding sites, ObjC classes / metaclasses / methods / categories,
                    as C tables for the runtime
"""
import os, sys, struct, re
sys.path.insert(0, os.path.dirname(__file__))
from macho import MachO

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
H = os.environ.get('MGST_HANDOFF') or os.path.join(ROOT, 'PORT_HANDOFF')
m = MachO(os.path.join(H, 'binary/MGSTUS'))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'build/gen')
os.makedirs(out, exist_ok=True)

IMG_LO, IMG_HI = 0x1000, 0x89000
img = bytearray(IMG_HI - IMG_LO)
for g in m.segments:
    if g.name in ('__TEXT', '__DATA'):
        img[g.vmaddr - IMG_LO: g.vmaddr - IMG_LO + g.vmsize] = m.read(g.vmaddr, g.vmsize)
open(os.path.join(out, 'image.bin'), 'wb').write(img)

binds = {}
for addr, sym, addend in m.external_relocs(): binds[addr] = (sym, addend)
for addr, sym, sect in m.indirect_bindings():
    if sect == '__nl_symbol_ptr': binds.setdefault(addr, (sym, 0))
bound = {a: s for a, (s, _) in binds.items()}

def ptr(addr):
    """Pointer field: ('local', value) or ('extern', symbol)."""
    if addr in bound: return ('extern', bound[addr])
    return ('local', m.u32(addr))

def methods(ml):
    if not ml: return []
    entsize, count = m.u32(ml) & ~3, m.u32(ml + 4)
    res = []
    for i in range(count):
        e = ml + 8 + i * entsize
        res.append((m.cstr(m.u32(e)), m.cstr(m.u32(e + 4)), m.u32(e + 8) & ~1))
    return res

def class_info(ca):
    ro = m.u32(ca + 16) & ~3
    flags, istart, isize = m.u32(ro), m.u32(ro + 4), m.u32(ro + 8)
    return dict(addr=ca, isa=ptr(ca), sup=ptr(ca + 4), name=m.cstr(m.u32(ro + 16)),
                flags=flags, istart=istart, isize=isize, methods=methods(m.u32(ro + 20)))

classes = []
cl = m.section('__DATA', '__objc_classlist')
for i in range(cl.size // 4):
    ca = m.u32(cl.addr + 4 * i)
    c = class_info(ca)
    assert c['isa'][0] == 'local', c['name']
    c['meta'] = class_info(c['isa'][1])
    classes.append(c)

cats = []
cs = m.section('__DATA', '__objc_catlist')
for i in range(cs.size // 4):
    ca = m.u32(cs.addr + 4 * i)
    cats.append(dict(name=m.cstr(m.u32(ca)), cls=ptr(ca + 4),
                     imethods=methods(m.u32(ca + 8)), cmethods=methods(m.u32(ca + 12))))

def cstr_lit(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def cref(p): return f'0x{p[1]:x}u, 0' if p[0] == 'local' else f'0, {cstr_lit(p[1])}'

L = ['/* generated by engine/tools/mk_image.py from PORT_HANDOFF/binary/MGSTUS - do not edit */',
     '#include "image_meta.h"', '']
L.append('const ImgBind img_binds[] = {')
for a in sorted(binds): L.append(f'  {{0x{a:x}u, {cstr_lit(binds[a][0])}, 0x{binds[a][1]:x}u}},')
L.append('};'); L.append(f'const int img_nbinds = {len(binds)};'); L.append('')
mid = 0
def emit_methods(name, ms):
    global mid
    L.append(f'static const ImgMethod {name}[] = {{')
    for sel, types, imp in ms: L.append(f'  {{{cstr_lit(sel)}, {cstr_lit(types)}, 0x{imp:x}u}},')
    L.append('  {0, 0, 0}};')
for i, c in enumerate(classes):
    emit_methods(f'im{i}', c['methods']); emit_methods(f'cm{i}', c['meta']['methods'])
L.append('const ImgClass img_classes[] = {')
for i, c in enumerate(classes):
    L.append(f'  {{{cstr_lit(c["name"])}, 0x{c["addr"]:x}u, 0x{c["meta"]["addr"]:x}u, {cref(c["sup"])}, '
             f'{cref(c["meta"]["isa"])}, {cref(c["meta"]["sup"])}, {c["istart"]}, {c["isize"]}, im{i}, cm{i}}},')
L.append('};'); L.append(f'const int img_nclasses = {len(classes)};'); L.append('')
for i, c in enumerate(cats):
    emit_methods(f'ci{i}', c['imethods']); emit_methods(f'cc{i}', c['cmethods'])
L.append('const ImgCategory img_categories[] = {')
for i, c in enumerate(cats): L.append(f'  {{{cstr_lit(c["name"])}, {cref(c["cls"])}, ci{i}, cc{i}}},')
L.append('};'); L.append(f'const int img_ncategories = {len(cats)};')
open(os.path.join(out, 'image_meta.c'), 'w').write('\n'.join(L) + '\n')

print(f'image.bin {len(img)} bytes; binds {len(binds)}; classes {len(classes)}; categories {len(cats)}; '
      f'methods {sum(len(c["methods"]) + len(c["meta"]["methods"]) for c in classes)}')
for c in cats: print('  category', c['name'], 'on', c['cls'], [x[0] for x in c['imethods'] + c['cmethods']])
ext_sup = sorted({c['sup'][1] for c in classes if c['sup'][0] == 'extern'})
print('  framework superclasses:', ext_sup)
