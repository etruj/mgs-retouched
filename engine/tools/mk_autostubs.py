#!/usr/bin/env python3
"""Weak stand-ins for every C import the game declares (build/imports.txt). A real
implementation in rt/ overrides the stub at link time; a stub that is still reached at
runtime logs its name once, so gaps show up in the log instead of as link errors."""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
out = ['/* generated by engine/tools/mk_autostubs.py */', '#include "mgst_types.fixed.h"',
       'void rt_stub_hit(const char *name);', '']
for line in open(src):
    line = line.strip()
    m = re.match(r'^(.*?)\b(_?\w+)\((.*)\);$', line)
    if not m: continue
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
    if name.startswith('_objc_msgSend') or '...' in args: continue
    body = f'rt_stub_hit("{name}");' + ('' if ret == 'void' else f' {{ {ret} __z; __builtin_memset(&__z, 0, sizeof __z); return __z; }}')
    out.append(f'__attribute__((weak)) {ret} {name}({args or "void"}) {{ {body} }}')
open(dst, 'w').write('\n'.join(out) + '\n')
